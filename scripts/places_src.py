PREFIX = ('인천 ', '시흥 ', '부천 ', '강서구 ', '구로구 ')


def strip_prefix(label):
    for p in PREFIX:
        if label.startswith(p):
            return label[len(p):]
    return label


def place_key(label):
    """키워드 지역 표기 → 장소 key"""
    if label in SIGU:
        return label
    if label in ALIAS:
        return ALIAS[label]
    return label  # 동·읍면은 표기 그대로 key


def places(labels):
    """키워드에 나온 (권역, 표기) 목록 → places dict"""
    out = {}
    for region, label in labels:
        key = place_key(label)
        if key in out:
            continue
        if key in SIGU:
            s = SIGU[key]
            out[key] = dict(key=key, name=key, **s)
            continue
        name = strip_prefix(label)
        gu, zone, ctx, memo = DONG[region][name]
        zr = Z[zone]
        admin = {'인천': f'인천 {gu} {name}' if gu else f'인천 {name}', '시흥': f'경기 시흥시 {name}', '부천': f'경기 부천시 {name}',
                 '강서구': f'서울 강서구 {name}', '구로구': f'서울 구로구 {name}'}[region]
        if name.endswith('면'):
            admin = f'인천 {gu} {name}'
        out[key] = dict(key=key, name=name, region=region, kind='동', zone=zone, ctx=ctx, admin=admin, gu=gu,
                        homes=zr['homes'], spots=zr['spots'][:3], note=memo)
    return out


